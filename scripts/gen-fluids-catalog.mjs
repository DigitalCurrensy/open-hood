function row(partial) {
  const modelIncludes = (partial.modelIncludes ?? [partial.model]).map((token) => String(token).toUpperCase());
  return {
    yearFrom: partial.yearFrom,
    yearTo: partial.yearTo,
    make: partial.make,
    model: partial.model,
    modelIncludes,
    oilViscosity: partial.oilViscosity,
    oilSpec: partial.oilSpec,
    oilCapacityQt: partial.oilCapacityQt,
    tirePsiFront: Number.isFinite(partial.tirePsiFront) ? `${partial.tirePsiFront} PSI` : partial.tirePsiFront,
    tirePsiRear: Number.isFinite(partial.tirePsiRear) ? `${partial.tirePsiRear} PSI` : partial.tirePsiRear,
    oilFilterSku: partial.oilFilterSku,
    airFilterSku: partial.airFilterSku,
    cabinFilterSku: partial.cabinFilterSku,
    coolant: partial.coolant,
    transmissionFluid: partial.transmissionFluid,
    brakeFluid: partial.brakeFluid,
    sparkPlugGap: partial.sparkPlugGap ?? "Confirm on the under-hood emissions label",
    notes: partial.notes ?? ["Door-jamb sticker owns tire PSI. Cap and manual own oil spec."],
  };
}

